"""Однообразие кадра: то, чего не видно на одном кадре, а зритель чувствует за минуту.

Ролики становятся одинаковыми не из-за анимации, а из-за композиции: один план, один фон, картинка стоит, пока идёт голос.
Здесь считается то, что на экране на самом деле: где стоят герои и какого они размера в настоящем кадре, а не что написано в сценарии.

  • один план три бита подряд;
  • один план или один фон занимает большую часть ролика;
  • больше ЗАСТОЙ_С секунд внутри бита ничего не меняется (фон на tick и субтитры сменой не считаются).

Бит для разбора: {'id', 'len', 'смены': [секунды], 'кадры': [{'t', 'фон', 'герои': [[x, y, масштаб], …]}, …]}.
"""
from collections import Counter

ПЛАНЫ = ('сверхкрупно', 'крупно', 'средний', 'общий', 'двое', 'лицом к лицу', 'через плечо', 'группа', 'сверху', 'комикс', 'экран', 'предмет', 'без героя')

КРУПНО = 1.7          # масштаб героя с этого значения: лицо занимает кадр
ОБЩИЙ = .8            # масштаб меньше этого: герой виден целиком в пространстве
СЛЕВА, СПРАВА = 320, 580   # границы центра кадра по x (ширина 900)
МАССОВКА = .5         # герой меньше главного в столько раз — это фон, а не второй участник сцены

ПОДРЯД_БИТОВ = 3      # столько битов одного плана подряд — уже замечание
ДОЛЯ_ПЛАНА = .5       # один план занимает такую долю ролика
ДОЛЯ_ФОНА = .8        # один фон занимает такую долю ролика
ЗАСТОЙ_С = 3.0        # столько секунд без единой смены картинки
МИН_РОЛИК = 15        # в ролике короче доли ничего не значат
ВСТАВКА = .6          # кусок короче (герой влетает, смена плана) серию не рвёт

СВОЙ_ФОН = 'свой фон'

JS_КАДР = """() => {
  const видно = el => {
    let o = 1;
    for (let n = el; n && n.id !== 'mm-svg'; n = n.parentNode) {
      if (!n.getAttribute) continue;
      if (n.getAttribute('display') === 'none') return false;
      const a = n.getAttribute('opacity'); if (a !== null) o *= parseFloat(a);
    }
    return o >= .2;
  };
  const герои = [...document.querySelectorAll('#mm-svg [data-hero]')].filter(видно).map(e => {
    const c = e.getScreenCTM();
    return [Math.round(c.e), Math.round(c.f), Math.round(Math.hypot(c.a, c.b) * 100) / 100];
  }).filter(([x, y]) => x > -100 && x < 1000 && y > -100 && y < 1700);
  const фоны = [...document.querySelectorAll('#mm-svg [data-bg]')].filter(видно);
  const метки = [...document.querySelectorAll('#mm-svg [data-plan]')].filter(видно);
  return { герои, фон: фоны.length ? фоны[фоны.length - 1].getAttribute('data-bg') : null, метка: метки.length ? метки[метки.length - 1].getAttribute('data-plan') : null };
}"""


def план(герои, метка=None):
    """Название плана по героям в кадре; главный — самый крупный. Планы, которых не распознать по героям, движок помечает сам (data-plan)."""
    if метка:
        return метка
    if not герои:
        return 'без героя'
    главный = max(герои, key=lambda г: г[2])
    участники = sum(1 for г in герои if г[2] >= главный[2] * МАССОВКА)
    if участники >= 3:
        return 'группа'
    if участники == 2:
        return 'двое'
    x, _, s = главный
    размер = 'крупно' if s >= КРУПНО else 'общий' if s < ОБЩИЙ else 'средний'
    место = 'слева' if x < СЛЕВА else 'справа' if x > СПРАВА else 'по центру'
    return f'{размер}, {место}'


def _план(кадр):
    return план(кадр['герои'], кадр.get('метка'))


def _вес(бит):
    return бит['len'] / max(len(бит['кадры']), 1)


def _серии(биты):
    """Подряд идущие куски одного плана: [план, секунды, [биты]]; короткие вставки не рвут серию."""
    куски = []
    for б in биты:
        for к in б['кадры']:
            п = _план(к)
            if not куски or куски[-1][0] != п:
                куски.append([п, 0.0, []])
            куски[-1][1] += _вес(б)
            if б['id'] not in куски[-1][2]:
                куски[-1][2].append(б['id'])
    серии = []
    for п, сек, ид in куски:
        if сек < ВСТАВКА:
            continue
        if серии and серии[-1][0] == п:
            серии[-1][1] += сек
            серии[-1][2].extend(i for i in ид if i not in серии[-1][2])
        else:
            серии.append([п, сек, ид])
    return серии


def _доли(биты, ключ):
    счёт = Counter()
    for б in биты:
        for к in б['кадры']:
            счёт[ключ(к)] += _вес(б)
    всего = sum(счёт.values()) or 1
    return [(имя, сек / всего) for имя, сек in счёт.most_common()]


def _застой(бит):
    точки = sorted({0.0, бит['len'], *(t for t in бит['смены'] if 0 <= t <= бит['len'])})
    return max((b - a for a, b in zip(точки, точки[1:])), default=0.0)


def замечания(биты, длительность):
    res = []
    for п, сек, ид in _серии(биты):
        if len(ид) >= ПОДРЯД_БИТОВ:
            имена = ', '.join(f'«{i}»' for i in ид)
            res.append(f'биты {имена} подряд сняты одним планом («{п}», {сек:.0f} с): смените план хотя бы в среднем из них')
    if длительность >= МИН_РОЛИК:
        for п, доля in _доли(биты, _план):
            if round(доля, 3) >= ДОЛЯ_ПЛАНА:
                res.append(f'план «{п}» занимает {доля:.0%} ролика: разбавьте другими планами (см. docs/scenes.md, раздел «Планы»)')
        for фон, доля in _доли(биты, lambda к: к['фон']):
            if фон and round(доля, 3) >= ДОЛЯ_ФОНА:
                res.append(f'фон «{фон}» занимает {доля:.0%} ролика: добавьте другое место или кадр без него')
    for б in биты:
        пауза = _застой(б)
        if пауза >= ЗАСТОЙ_С:
            res.append(f'бит «{б["id"]}»: {пауза:.1f} с подряд в кадре ничего не меняется: смените план, эмоцию или покажите новое')
    return res


def сводка(биты):
    """Одна строка для агента: на что ушло время ролика."""
    планы = ' · '.join(f'{п} {доля:.0%}' for п, доля in _доли(биты, _план))
    фоны = ' · '.join(f'{ф or СВОЙ_ФОН} {доля:.0%}' for ф, доля in _доли(биты, lambda к: к['фон']))
    return f'Планы: {планы}. Фоны: {фоны}.'
