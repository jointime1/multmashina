def _основа(слово):
    return слово.lower().replace('ё', 'е')[:ОСНОВА]


def _слова(текст):
    текст = re.sub(r'\[\[[^\]]*\]\]', ' ', текст)                 # метки [[имя]] — разметка, а не слова
    return re.findall(r'[A-Za-zА-Яа-яЁё]{%d,}' % МИН_ДЛИНА, текст)


_ЧАСТЫЕ_ОСНОВЫ = {_основа(w) for w in ЧАСТЫЕ}


def чужие_слова(источник, тексты):
    """Слова из `тексты` [(бит, где, текст), …], которых нет в `источник`: [{слово, бит, где}], каждое слово один раз, в порядке появления."""
    свои = {_основа(w) for w in re.findall(r'[A-Za-zА-Яа-яЁё]+', источник)}
    найдено, видели = [], set()
    for бит, где, текст in тексты:
        for слово in _слова(текст):
            о = _основа(слово)
            if о in свои or о in _ЧАСТЫЕ_ОСНОВЫ or о in видели:
                continue
            видели.add(о)
            найдено.append({'слово': слово, 'бит': бит, 'где': где})
    return найдено


_ВЫЗОВ = re.compile(r"""\b(?:label|word|stamp|note|T)\(\s*[\w.$]+\s*,\s*(['"`])((?:(?!\1).)+)\1""")
_МАССИВ = re.compile(r"""\[\s*(['"`])([^'"`]{3,}?)\1\s*,\s*-?[\d.]""")
_БИТ = re.compile(r"""^\s*\[\s*['"]([^'"]+)['"]\s*,\s*['"]""")


def надписи_сцен(js):
    """Надписи, которые сцены рисуют на экране: [(бит, текст), …]. Бит определяется по ближайшей выше строке вида `['бит', 'Название', …`."""
    бит, res = None, []
    for строка in js.splitlines():
        m = _БИТ.match(строка)
        if m:
            бит = m.group(1)
            continue
        for rx in (_ВЫЗОВ, _МАССИВ):
            for найдено in rx.finditer(строка):
                res.append((бит, найдено.group(2)))
    return res


def замечания(источник, биты, js=''):
    """Замечания проверки: слова ролика (реплики `биты` {бит: текст} и надписи сцен `js`), которых нет в источнике."""
    if len(re.findall(r'\w+', источник)) < МИН_СЛОВ_В_ИСТОЧНИКЕ:
        return []
    тексты = [(б, 'речь', t) for б, t in биты.items()] + [(б, 'надпись', t) for б, t in надписи_сцен(js)]
    найдено = чужие_слова(источник, тексты)
    if not найдено:
        return []
    список = ', '.join(f'{x["слово"]} ({x["где"]}, бит «{x["бит"]}»)' for x in найдено[:МАКС_В_ЗАМЕЧАНИИ])
    ещё = f' и ещё {len(найдено) - МАКС_В_ЗАМЕЧАНИИ}' if len(найдено) > МАКС_В_ЗАМЕЧАНИИ else ''
    return [f'слов нет в источнике.md: {список}{ещё}. Это пересказ или выдумка? Шутка должна расти из материала; '
            'слова «из головы» (профессиональные клише темы) замените на то, что было в источнике, или покажите человеку, что это ваше']
