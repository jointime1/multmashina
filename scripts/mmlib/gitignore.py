"""Снятое и собранное в коммит не идёт: рядом с видео, кадрами проверки, сборкой и сырой озвучкой движок кладёт .gitignore.

Проект человека обычно живёт в чужом git-репозитории (рилсы рядом с кодом продукта), где про out/, build/ и review/ никто не знает,
и один `git add -A` утащил бы в коммит гигабайты видео. Поэтому там, где движок что-то создаёт, он сам спрашивает у git, видно ли это,
и если видно, то дописывает в папку .gitignore (так делают pytest и venv). Вне git-репозитория и там, где всё уже игнорируется
(например в репозитории самого движка), ничего не создаётся. Чужие строки в .gitignore не трогаются.
"""
import subprocess
from pathlib import Path

ШАПКА = '# Мультмашина: снятое и собранное в коммит не идёт. Хотите коммитить такие файлы — уберите строку.'


def игнорируется(папка, шаблон):
    """True: git уже не покажет файл по такому шаблону; False: покажет; None: папка не в git-репозитории (или git не установлен)."""
    проба = Path(папка) / шаблон.replace('*', '_')
    try:
        r = subprocess.run(['git', '-C', str(папка), 'check-ignore', '-q', '--', str(проба)], capture_output=True)
    except OSError:
        return None
    return {0: True, 1: False}.get(r.returncode)


def скрыть_от_git(папка, *шаблоны):
    """Допишет в <папка>/.gitignore те шаблоны, которые git пока не игнорирует; папка уже должна существовать. Вернёт дописанное."""
    папка = Path(папка).resolve()
    файл = папка / '.gitignore'
    текст = файл.read_text(encoding='utf-8') if файл.exists() else ''
    строки = set(текст.splitlines())
    нужно = [ш for ш in шаблоны
             if ш not in строки and f'!{ш}' not in строки          # «!шаблон» — осознанное решение человека коммитить такое
             and игнорируется(папка, ш) is False]
    if not нужно:
        return []
    if текст and not текст.endswith('\n'):
        текст += '\n'
    if ШАПКА not in строки:
        текст += ШАПКА + '\n'
    файл.write_text(текст + '\n'.join(нужно) + '\n', encoding='utf-8')
    print(f'Положил {файл}: {", ".join(нужно)} в коммит не попадут')
    return нужно
