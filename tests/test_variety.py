@pytest.mark.browser
def test_разнообразный_ролик_проходит_строгую_проверку(мини, в_пустой, capsys):
    """Контроль с другой стороны: проверка не бракует всё подряд, хороший ролик длиннее 15 с проходит."""
    эмоции = "[[0, 'neutral'], [1.5, 'shock'], [3, 'grin']]"
    _эпизод(мини, {
        'a': f"room(s, 'комната'); hero(s, 'петя', CX, 870, 2.4, {эмоции}, 0, D);",
        'b': "const t = term(s, 90, 340, 720, 420, 'терминал', 0); termLine(t, 'раз', 44, 170, 1.4, '#fff', 50); termLine(t, 'два', 44, 270, 2.8, '#fff', 50);",
        'c': f"office(s, {{ name: 'Контора' }}); hero(s, 'петя', 230, 1000, .95, {эмоции}, 0, D); hero(s, 'петя', 670, 1000, .95, {эмоции}, 0, D); desk(s);",
        'd': f"room(s, 'подвал'); hero(s, 'петя', CX, 1080, .6, {эмоции}, 0, D); desk(s);",
    }, длит=4)
    код, вывод = _проверить(мини, capsys, строго=True)
    assert код == 0 and 'Замечание' not in вывод, вывод
    assert 'крупно, по центру 25%' in вывод and 'без героя 25%' in вывод and 'двое 25%' in вывод and 'общий, по центру 25%' in вывод, вывод


