from mmlib import config, variety

СРЕДНИЙ = [[450, 1000, 1.3]]
СЛЕВА = [[220, 1000, 1.2]]
КРУПНО = [[450, 900, 2.2]]
ОБЩИЙ = [[450, 900, .6]]
ДВОЕ = [[230, 1000, .95], [670, 1000, .95]]
ГРУППА = [[200, 1000, .8], [450, 1000, .8], [700, 1000, .8]]


def бит(id_, герои, фон='комната', длина=5.0, смены=(0, 1.5, 3)):
    шаг = .25
    return {'id': id_, 'len': длина, 'смены': list(смены),
            'кадры': [{'t': i * шаг, 'фон': фон, 'герои': герои} for i in range(int(длина / шаг) + 1)]}


def ролик(*биты):
    return sum(b['len'] for b in биты), list(биты)


# ---------- план кадра ----------

@pytest.mark.parametrize('герои, ожидается', [
    (СРЕДНИЙ, 'средний, по центру'),
    (СЛЕВА, 'средний, слева'),
    ([[700, 1000, 1.2]], 'средний, справа'),
    (КРУПНО, 'крупно, по центру'),
    (ОБЩИЙ, 'общий, по центру'),
    (ДВОЕ, 'двое'),
    (ГРУППА, 'группа'),
    ([], 'без героя'),
])
def test_план_кадра(герои, ожидается):
    assert variety.план(герои) == ожидается


def test_массовка_на_заднем_плане_не_делает_кадр_двойным():
    assert variety.план([[450, 1000, 1.3], [120, 800, .4]]) == 'средний, по центру'


def test_все_планы_описаны_в_справочнике():
    t = (config.ROOT / 'docs' / 'scenes.md').read_text(encoding='utf-8')
    for имя in variety.ПЛАНЫ:
        assert f'`{имя}`' in t, f'план «{имя}» не описан в docs/scenes.md'


# ---------- замечания ----------

def test_один_план_в_трёх_битах_подряд():
    длит, биты = ролик(бит('a', СРЕДНИЙ), бит('b', СРЕДНИЙ), бит('c', СРЕДНИЙ), бит('d', КРУПНО), бит('e', ДВОЕ), бит('f', ОБЩИЙ))
    серии = [z for z in variety.замечания(биты, длит) if 'подряд' in z]
    assert len(серии) == 1, серии
    assert all(f'«{id_}»' in серии[0] for id_ in 'abc') and '«d»' not in серии[0]


def test_короткая_вставка_не_рвёт_серию():
    длит, биты = ролик(бит('a', СРЕДНИЙ), бит('b', КРУПНО, длина=.25), бит('c', СРЕДНИЙ), бит('d', СРЕДНИЙ), бит('e', ДВОЕ), бит('f', ОБЩИЙ))
    assert any('подряд' in z for z in variety.замечания(биты, длит))


def test_разные_планы_проходят_без_замечаний():
    длит, биты = ролик(бит('a', СРЕДНИЙ), бит('b', КРУПНО, фон='офис'), бит('c', ДВОЕ), бит('d', ОБЩИЙ, фон='офис'), бит('e', [], фон=None))
    assert variety.замечания(биты, длит) == []


def test_перекос_в_один_план_через_весь_ролик():
    длит, биты = ролик(бит('a', СРЕДНИЙ), бит('b', КРУПНО, фон='офис'), бит('c', СРЕДНИЙ), бит('d', ДВОЕ, фон='офис'), бит('e', СРЕДНИЙ), бит('f', ОБЩИЙ, фон='офис'),
                       бит('g', СРЕДНИЙ), бит('h', СРЕДНИЙ, фон='офис', длина=.5))
    z = [x for x in variety.замечания(биты, длит) if 'занимает' in x and 'средний, по центру' in x]
    assert len(z) == 1 and '%' in z[0]


def test_перекос_в_один_фон():
    длит, биты = ролик(бит('a', СРЕДНИЙ), бит('b', КРУПНО), бит('c', ДВОЕ), бит('d', ОБЩИЙ), бит('e', [], фон='офис'))
    z = [x for x in variety.замечания(биты, длит) if 'фон' in x]
    assert len(z) == 1 and '«комната»' in z[0]


def test_свой_фон_не_считается_одним_и_тем_же():
    длит, биты = ролик(*[бит(id_, п, фон=None) for id_, п in zip('abcde', [СРЕДНИЙ, КРУПНО, ДВОЕ, ОБЩИЙ, СЛЕВА])])
    assert variety.замечания(биты, длит) == []


def test_застывшая_картинка_внутри_бита():
    длит, биты = ролик(бит('a', СРЕДНИЙ, длина=6, смены=(0, 4.5)))
    z = variety.замечания(биты, длит)
    assert len(z) == 1 and 'бит «a»' in z[0] and '4.5' in z[0], z


def test_застой_считается_и_после_последней_смены():
    длит, биты = ролик(бит('a', СРЕДНИЙ, длина=6, смены=(0, 1)))
    assert any('бит «a»' in z and '5.0' in z for z in variety.замечания(биты, длит))


def test_частые_смены_не_застой():
    длит, биты = ролик(бит('a', СРЕДНИЙ, длина=6, смены=(0, 1.5, 3, 4.5)))
    assert variety.замечания(биты, длит) == []


def test_в_коротком_ролике_доли_не_считаются():
    длит, биты = ролик(бит('a', СРЕДНИЙ, длина=2, смены=(0,)))
    assert variety.замечания(биты, длит) == []


def test_сводка_называет_доли_планов_и_фонов():
    _, биты = ролик(бит('a', СРЕДНИЙ), бит('b', КРУПНО), бит('c', [], фон=None), бит('d', ДВОЕ, фон='офис'))
    t = variety.сводка(биты)
    assert 'средний, по центру 25%' in t and 'без героя 25%' in t and 'комната 50%' in t and 'свой фон 25%' in t


