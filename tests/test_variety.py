ОБОЛОЧКА = """'use strict';
const BEATS = [%s];
start(BEATS);
"""
БИТ = """['%s', 'Тест', (m, D) => { const p = panel(0), s = shot(p, 0, undefined, { bg: DARK }); %s finish(p); caps(p, '%s'); }]"""


def _эпизод(папка, сцены, длит=1.5, слов=3):
    """Эпизод из битов {id: js}; тишина вместо голоса длиной длит."""
    import json
    if not shutil.which('ffmpeg'):
        pytest.skip('нужен ffmpeg')
    (папка / 'scenes.js').write_text(ОБОЛОЧКА % ',\n'.join(БИТ % (id_, js, id_) for id_, js in сцены.items()), encoding='utf-8')
    (папка / 'narration.yaml').write_text('биты:\n' + ''.join(f'  {id_}: "[[a]]Слово один."\n' for id_ in сцены), encoding='utf-8')
    (папка / 'audio').mkdir(exist_ok=True)
    тайминги = {}
    for id_ in сцены:
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'lavfi', '-i', 'anullsrc=r=44100:cl=mono', '-t', str(длит), '-codec:a', 'libmp3lame',
                        str(папка / 'audio' / f'{id_}.mp3')], check=True)
        тайминги[id_] = {'dur': длит, 'marks': {'a': .1}, 'words': [[.1 + длит * i / слов, f'слово{i}'] for i in range(слов)]}
    (папка / 'audio' / 'timings.json').write_text(json.dumps(тайминги, ensure_ascii=False), encoding='utf-8')


