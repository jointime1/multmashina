def _проверить(папка, capsys, **kw):
    from mmlib import check
    try:
        код = check.проверить(папка, **kw)
    except Exception as e:
        if 'Executable' in str(e):
            pytest.skip(f'нет Chromium: {e}')
        raise
    return код, capsys.readouterr().out


