"""Сверка сценария с источником: выдуманные шутки и «типичные для темы» слова, которых в материале не было."""
from mmlib import source

ЧАТ = """Пацаны, новая тема: бросайте айтишку и го тупить. Будем рвать шлейфы, вырезать по дереву, пить пиво на Волге.
Я в неё ещё даже не попал, а уже бросать. Изучение бэкенда регулярно вызывает это желание."""


def test_выдуманное_слово_находится():
    найдено = source.чужие_слова(ЧАТ, [('quit', 'речь', 'Все пошли деплоить.')])
    assert [x['слово'] for x in найдено] == ['деплоить']
    assert найдено[0]['бит'] == 'quit' and найдено[0]['где'] == 'речь'


def test_склонения_слов_источника_не_считаются_чужими():
    # «дереву» в источнике, «деревом» в ролике: общая основа
    assert source.чужие_слова(ЧАТ, [('quit', 'речь', 'Вырезать будем перед деревом.')]) == []


def test_метки_и_короткие_слова_не_мешают():
    assert source.чужие_слова(ЧАТ, [('quit', 'речь', '[[man]]Бросайте айтишку, а я в неё не попал.')]) == []


def test_обычные_слова_русского_языка_не_считаются_выдумкой():
    assert source.чужие_слова(ЧАТ, [('quit', 'речь', 'Потом, который раз, только сначала сказал: теперь можно.')]) == []


def test_числа_прописью_и_дни_недели_не_считаются_выдумкой():
    # в источнике «98» и «в субботу» цифрами и в другой форме, а ролик говорит словами
    assert source.чужие_слова(ЧАТ, [('a', 'речь', 'В понедельник девяносто восемь, двадцать четыре, четыре человека.')]) == []


def test_надпись_на_латинице_тоже_проверяется():
    найдено = source.чужие_слова(ЧАТ, [('quit', 'надпись', 'DEPLOY')])
    assert [x['слово'] for x in найдено] == ['DEPLOY'] and найдено[0]['где'] == 'надпись'


def test_слово_называется_один_раз_даже_если_повторяется():
    найдено = source.чужие_слова(ЧАТ, [('a', 'речь', 'Миграции, миграции.'), ('b', 'надпись', 'МИГРАЦИИ')])
    assert [x['слово'] for x in найдено] == ['Миграции'] and найдено[0]['бит'] == 'a'


def test_надписи_берутся_из_вызовов_сцен_по_битам():
    js = """const BEATS = [
  ['quit', 'Бросайте', (m, D) => {
    word(a, 'МАНИФЕСТ', ...k.text, m('man'), { size: 90 });
    label(b, 'DEPLOY', CX, 440, t + .2, { size: 110 });
    stamp(b, `ВСЕ НА МЕСТЕ`, CX, 760, 1, { size: 80 });
  }],
  ['hook', 'Хук', (m, D) => {
    [['а вы видели?', 230, 860, .9], ['нет', 650, 910, 1.5]].forEach(([tx, x, y, t]) => label(s, tx, x, y, t, {}));
  }],
];"""
    надписи = source.надписи_сцен(js)
    assert ('quit', 'МАНИФЕСТ') in надписи and ('quit', 'DEPLOY') in надписи and ('quit', 'ВСЕ НА МЕСТЕ') in надписи
    assert ('hook', 'а вы видели?') in надписи
    assert all(бит != 'hook' or текст != 'DEPLOY' for бит, текст in надписи)


def test_замечание_перечисляет_слова_и_где_они_стоят():
    js = "const BEATS = [\n  ['quit', 'Б', (m, D) => {\n    label(b, 'DEPLOY', CX, 440, 1, {});\n  }],\n];"
    z = source.замечания(ЧАТ, {'quit': 'Все пошли деплоить.'}, js)
    assert len(z) == 1
    assert 'деплоить' in z[0] and 'DEPLOY' in z[0] and 'quit' in z[0] and 'источник' in z[0].lower()


def test_без_чужих_слов_замечаний_нет():
    assert source.замечания(ЧАТ, {'quit': 'Бросайте айтишку, пить пиво на Волге.'}, '') == []


def test_пустой_источник_не_проверяется():
    # заготовка с парой слов не повод ругаться на каждое слово ролика
    assert source.замечания('# Источник\n\nВставьте сюда материал.', {'a': 'Совсем другие слова здесь.'}, '') == []
