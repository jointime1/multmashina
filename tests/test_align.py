import pytest

from mmlib.voice.align import время_меток, разобрать_метки


def test_метки_и_чистый_текст():
    чистый, метки = разобрать_метки('[[a]]Привет, [[b]]мир.')
    assert чистый == 'Привет, мир.'
    assert метки == {'a': 0, 'b': 8}


def test_повтор_метки_запрещён():
    with pytest.raises(ValueError, match='повторяется'):
        разобрать_метки('[[a]]раз [[a]]два')


def test_время_метки_это_начало_слова():
    чистый, метки = разобрать_метки('[[a]]Привет, [[b]]мир.')
    assert время_меток(чистый, метки, [[0.1, 'Привет'], [0.9, 'мир']]) == {'a': 0.1, 'b': 0.9}


def test_метка_без_слова_ошибка():
    чистый, метки = разобрать_метки('раз [[x]]два')
    with pytest.raises(ValueError, match='не совпала'):
        время_меток(чистый, метки, [[0.1, 'раз']])
