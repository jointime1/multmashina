/* scenes.js — сцены эпизода «{{название}}». Справочник по всем вызовам и планам — docs/scenes.md.
   Бит = [id, название, (m, D) => { … }, {pre}]: m('метка') — время слова, D — длина реплики, всё внутри от нуля.
   Слова держите в зоне x 50–810, y 130–1290: платформы закрывают остальное кнопками.
   Каждый бит снят своим планом из раскадровка.md: собирайте сцену по таблице, а не копируйте соседнюю. */
'use strict';

const BEATS = [
  // План «крупно»: лицо на весь кадр, первый кадр уже в движении. План сам ставит героя и подсказывает место под надпись (k.text, k.size)
  ['hook', 'Хук', (m, D) => {
    const p = panel(), s = shot(p, 0, undefined, { bg: DARK });
    room(s, 'комната');
    const k = closeUp(s, 'главный', [[0, 'neutral'], [m('a'), 'smug'], [m('b'), 'grin']], 0, D);
    word(s, 'мир', ...k.text, m('b'), { size: k.size, fill: MARK, stroke: DARK });        // слово вылетает, когда звучит «мир»
    finish(p); caps(p, 'hook');                                                           // зерно/виньетка, затем субтитры
  }],

  // План «экран»: событие показывает сама переписка
  ['middle', 'Середина', (m, D) => {
    const p = panel(), s = shot(p, 0, undefined, { bg: DARK });
    chat(s, 'Начальник', [[0, 'Ты где?', .1], [1, 'Уже бегу', .5], [0, 'Не беги', m('c')]]);
    stamp(s, 'ВАУ', CX, 960, m('c'), { size: 120, colour: RED });
    finish(p); caps(p, 'middle');
  }],

  // План «средний, слева»: герой за столом, рядом свободное место (k.side)
  ['outro', 'Финал', (m, D) => {
    const p = panel(), s = shot(p, 0, undefined, { bg: DARK });
    room(s, 'подвал');
    const k = medium(s, 'главный', [[0, 'grin', { wink: 1 }]], 0, D);
    label(s, 'подписывайтесь', ...k.text, m('d'), { size: 80, fill: MARK, colour: DARK });
    finish(p); caps(p, 'outro');
  }],
];

start(BEATS);
