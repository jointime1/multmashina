/* scenes.js — сцены эпизода «{{название}}». Справочник по всем вызовам и планам — docs/scenes.md.
   Бит = [id, название, (m, D) => { … }, {pre}]: m('метка') — время слова, D — длина реплики, всё внутри от нуля.
   Слова держите в зоне x 50–810, y 130–1290: платформы закрывают остальное кнопками.
   Каждый бит снят своим планом из раскадровка.md: собирайте сцену по таблице, а не копируйте соседнюю. */
'use strict';

const BEATS = [
  // План «крупно»: лицо на весь кадр, первый кадр уже в движении
  ['hook', 'Хук', (m, D) => {
    const p = panel(), s = shot(p, 0, undefined, { bg: DARK });
    room(s, 'комната');
    hero(s, 'главный', CX, 870, 2.4, [[0, 'neutral'], [m('a'), 'smug'], [m('b'), 'grin']], 0, D);
    word(s, 'мир', CX, 235, m('b'), { size: 130, fill: MARK, stroke: DARK });           // слово вылетает, когда звучит «мир»
    finish(p); caps(p, 'hook');                                                           // зерно/виньетка, затем субтитры
  }],

  // План «без героя»: событие показывает сам предмет (экран, документ, число)
  ['middle', 'Середина', (m, D) => {
    const p = panel(), s = shot(p, 0, undefined, { bg: DARK });
    const t = term(s, 90, 340, 720, 420, 'терминал', 0);
    termLine(t, '$ запуск', 44, 170, .2, '#e2e8f0', 50);
    termLine(t, 'ошибка: всё пропало', 44, 270, m('c'), '#ff3b3b', 50);
    stamp(s, 'ВАУ', CX, 960, m('c'), { size: 120, colour: RED });
    finish(p); caps(p, 'middle');
  }],

  // План «средний, слева»: герой сбоку, рядом то, о чём он говорит
  ['outro', 'Финал', (m, D) => {
    const p = panel(), s = shot(p, 0, undefined, { bg: DARK });
    room(s, 'подвал');
    hero(s, 'главный', 260, 950, 1.2, [[0, 'grin', { wink: 1 }]], 0, D);
    desk(s);                                                                              // закрывает нижний край торса: ног у героя нет
    label(s, 'подписывайтесь', CX, 480, m('d'), { size: 80, fill: MARK, colour: DARK });
    finish(p); caps(p, 'outro');
  }],
];

start(BEATS);
